/**
 * grimdark-derived.ts — the bases of Grimdark that are built from FMG's
 * own name bases.
 *
 * Grimdark is Dune and Warhammer 40K with the serial numbers filed off.
 * The register is: the Imperium of Man (its Latin, Nordic, Finnic and
 * Levantine provinces), the ancient machine empires that predate it (the
 * Precursors), the Weavers and their dark kin, the Chaos legions, and the
 * swarms.
 *
 * We do not write those pools by hand — we take FMG's, and add the one
 * thing FMG has no place for: the words the people call their polities by.
 *
 * The base names carry the **Grimdark** prefix on purpose, the same reason
 * the Trek ones carry "Trek": FMG's own array already holds a base called
 * "Elven", and a base of ours with the same name would replace the stock
 * base in place and change what FMG's own culture sets generate.
 */
