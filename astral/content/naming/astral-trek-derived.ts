/**
 * astral-trek-derived.ts — the bases of AstralTrek that are built from
 * FMG's own name bases.
 *
 * Azgaar ships 43 name bases; a dozen of them are the vocabularies this
 * set wants: the real-world ones (English, German, Chinese, Nigerian,
 * Vietnamese, Arabic, Karnataka) and the fantasy ones (Orc, Goblin, Elven,
 * Dark Elven, Arachnid). We do not write those pools by hand — we take
 * FMG's, and add the one thing FMG has no place for: the words the people
 * call their polities by.
 *
 * The base names carry the **Trek** prefix on purpose. FMG's own array
 * already holds a base called "English"; if ours had the same name, the
 * mod's merge would replace the stock base in place and change what
 * FMG's own culture sets generate. Ours are appended instead, so a stock
 * base is never displaced, and a saved map keeps its indices.
 */
